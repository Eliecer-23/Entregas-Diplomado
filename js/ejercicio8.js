/**el mismo ejercico de tres formas */
/**Inicio ejerccion 8 */
{
    /**for */
for (let i = 10; i >= 1; i-- ) {
    document.write("Numero: " + i + "<br>");
    }
}

{
    /**while */
let i = 10;
while (i >= 1) {
    document.write("Numero: "+ i + "<br>");
    i--;
    }
}

{
/**do while*/
let i = 10;
do {
    document.write("Numero: " + i + "<br>");
    i--;
    } while (i >= 1);
}